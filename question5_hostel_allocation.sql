CREATE OR REPLACE FUNCTION fn_free_beds(p_room_id INT)
RETURNS INT LANGUAGE plpgsql AS $$
DECLARE v_capacity INT; v_occupied INT;
BEGIN
 SELECT capacity INTO v_capacity FROM rooms WHERE room_id=p_room_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room ID %',p_room_id; END IF;
 SELECT COUNT(*) INTO v_occupied FROM allocations WHERE room_id=p_room_id AND status='ACTIVE';
 RETURN v_capacity-v_occupied;
END $$;

CREATE OR REPLACE FUNCTION fn_enforce_allocation_rules()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_capacity INT; v_occupied INT;
BEGIN
 IF NEW.status='ACTIVE' THEN
  -- Lock room and student rows so concurrent allocations cannot exceed limits.
  SELECT capacity INTO v_capacity FROM rooms WHERE room_id=NEW.room_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room'; END IF;
  PERFORM 1 FROM students WHERE student_id=NEW.student_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown student'; END IF;
  SELECT COUNT(*) INTO v_occupied FROM allocations a
   WHERE a.room_id=NEW.room_id AND a.status='ACTIVE'
   AND (TG_OP='INSERT' OR a.allocation_id<>NEW.allocation_id);
  IF v_occupied>=v_capacity THEN RAISE EXCEPTION 'Room capacity has been reached'; END IF;
  IF EXISTS(SELECT 1 FROM allocations a WHERE a.student_id=NEW.student_id
    AND a.status='ACTIVE' AND (TG_OP='INSERT' OR a.allocation_id<>NEW.allocation_id)) THEN
   RAISE EXCEPTION 'Student already has an ACTIVE allocation';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_allocation_rules BEFORE INSERT OR UPDATE ON allocations
FOR EACH ROW EXECUTE FUNCTION fn_enforce_allocation_rules();

CREATE OR REPLACE PROCEDURE pr_allocate_room(p_student_id INT,p_room_id INT,p_allocated_on DATE)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM students WHERE student_id=p_student_id) THEN RAISE EXCEPTION 'Unknown student'; END IF;
 IF NOT EXISTS(SELECT 1 FROM rooms WHERE room_id=p_room_id) THEN RAISE EXCEPTION 'Unknown room'; END IF;
 IF p_allocated_on IS NULL THEN RAISE EXCEPTION 'Allocation date is required'; END IF;
 IF EXISTS(SELECT 1 FROM allocations WHERE student_id=p_student_id AND status='ACTIVE') THEN
  RAISE EXCEPTION 'Student already has an ACTIVE allocation';
 END IF;
 IF fn_free_beds(p_room_id)<=0 THEN RAISE EXCEPTION 'Room has no free beds'; END IF;
 INSERT INTO allocations(student_id,room_id,allocated_on,released_on,status)
 VALUES(p_student_id,p_room_id,p_allocated_on,NULL,'ACTIVE');
END $$;

