CREATE TABLE patients(patient_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name VARCHAR(120) NOT NULL);
CREATE TABLE doctors(doctor_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,full_name VARCHAR(120) NOT NULL);
CREATE TABLE appointments(
 appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id INT NOT NULL REFERENCES patients,doctor_id INT NOT NULL REFERENCES doctors,
 appointment_day DATE NOT NULL,slot_time TIME NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'BOOKED' CHECK(status IN('BOOKED','ATTENDED','CANCELLED')),
 CHECK(slot_time IN(TIME '09:00',TIME '10:00',TIME '11:00',TIME '12:00'))
);
CREATE TABLE clinic_summary(
 summary_date DATE PRIMARY KEY,booked_count BIGINT NOT NULL,
 attended_count BIGINT NOT NULL,cancelled_count BIGINT NOT NULL
);
