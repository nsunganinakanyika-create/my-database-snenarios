CREATE OR REPLACE VIEW v_farmer_amount_due AS
SELECT f.farmer_number,f.full_name,COALESCE(SUM(d.total_value) FILTER(WHERE d.is_paid=FALSE),0)::NUMERIC(14,2) AS amount_due
FROM farmers f LEFT JOIN deliveries d USING(farmer_id)
GROUP BY f.farmer_id,f.farmer_number,f.full_name;

CREATE INDEX idx_deliveries_farmer_date ON deliveries(farmer_id,delivered_on);
EXPLAIN SELECT * FROM deliveries WHERE farmer_id=1
 AND delivered_on>=CURRENT_DATE-30 AND delivered_on<CURRENT_DATE+1;

CREATE OR REPLACE PROCEDURE pr_refresh_purchases(p_day DATE)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_day IS NULL THEN RAISE EXCEPTION 'Purchase date cannot be NULL'; END IF;
 INSERT INTO daily_purchases(purchase_date,total_weight,total_value)
 SELECT p_day,COALESCE(SUM(weight_kg),0),COALESCE(SUM(total_value),0)
 FROM deliveries WHERE delivered_on=p_day
 ON CONFLICT(purchase_date) DO UPDATE SET
 total_weight=EXCLUDED.total_weight,total_value=EXCLUDED.total_value;
END $$;
CALL pr_refresh_purchases(CURRENT_DATE);
