CREATE SCHEMA IF NOT EXISTS ict371_q6;
SET search_path TO ict371_q6,public;

CREATE TABLE employees(
 employee_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL,
 basic_salary NUMERIC(12,2) NOT NULL CHECK(basic_salary>=0),
 allowance NUMERIC(12,2) NOT NULL CHECK(allowance>=0),
 deduction NUMERIC(12,2) NOT NULL CHECK(deduction>=0),
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE payroll(
 payroll_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id INT NOT NULL REFERENCES employees,
 pay_month DATE NOT NULL CHECK(EXTRACT(DAY FROM pay_month)=1),
 gross_pay NUMERIC(12,2) NOT NULL CHECK(gross_pay>=0),
 net_pay NUMERIC(12,2) NOT NULL CHECK(net_pay>=0),
 UNIQUE(employee_id,pay_month)
);
CREATE TABLE salary_audit(
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id INT NOT NULL REFERENCES employees,
 old_salary NUMERIC(12,2) NOT NULL,new_salary NUMERIC(12,2) NOT NULL,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
