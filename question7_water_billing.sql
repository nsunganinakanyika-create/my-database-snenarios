CREATE OR REPLACE FUNCTION fn_water_charge(p_units NUMERIC)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
 IF p_units IS NULL OR p_units<0 THEN RAISE EXCEPTION 'Consumption cannot be NULL or negative'; END IF;
 RETURN ROUND(LEAST(p_units,10)*5 + GREATEST(p_units-10,0)*8,2);
END $$;

CREATE OR REPLACE FUNCTION fn_validate_reading()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.previous_reading IS NULL OR NEW.current_reading IS NULL
  OR NEW.previous_reading<0 OR NEW.current_reading<NEW.previous_reading THEN
  RAISE EXCEPTION 'Current meter reading must be at least the previous reading; values cannot be negative';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_validate_reading BEFORE INSERT OR UPDATE ON readings
FOR EACH ROW EXECUTE FUNCTION fn_validate_reading();

