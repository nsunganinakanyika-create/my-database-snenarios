CREATE OR REPLACE FUNCTION fn_scholarship_eligible(p_age INT,p_income NUMERIC,p_mark NUMERIC)
RETURNS BOOLEAN LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
 IF p_age IS NULL OR p_income IS NULL OR p_mark IS NULL THEN RAISE EXCEPTION 'Eligibility inputs cannot be NULL'; END IF;
 IF p_age<=0 OR p_income<0 OR p_mark<0 OR p_mark>100 THEN RAISE EXCEPTION 'Invalid age, income or mark'; END IF;
 RETURN p_age BETWEEN 18 AND 25 AND p_income<=3000 AND p_mark>=70;
END $$;

CREATE OR REPLACE FUNCTION fn_audit_decision()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.status IS DISTINCT FROM NEW.status THEN
  INSERT INTO decision_audit(application_id,old_status,new_status)
  VALUES(NEW.application_id,OLD.status,NEW.status);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_decision_audit AFTER UPDATE OF status ON applications
FOR EACH ROW EXECUTE FUNCTION fn_audit_decision();

CREATE OR REPLACE PROCEDURE pr_assess_application(p_application_id BIGINT)
LANGUAGE plpgsql AS $$
DECLARE r RECORD;v_status VARCHAR(10);
BEGIN
 SELECT age_at_application,monthly_income,average_mark,status
 INTO r FROM applications WHERE application_id=p_application_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown application ID %',p_application_id; END IF;
 IF r.status<>'PENDING' THEN RAISE EXCEPTION 'Application % has already been assessed',p_application_id; END IF;
 IF fn_scholarship_eligible(r.age_at_application,r.monthly_income,r.average_mark) THEN
  v_status:='APPROVED';
 ELSE
  v_status:='REJECTED';
 END IF;
 UPDATE applications SET status=v_status WHERE application_id=p_application_id;
END $$;

CREATE OR REPLACE VIEW v_approved_applicants AS
SELECT s.student_number,s.full_name,a.average_mark,a.status
FROM applications a JOIN students s USING(student_id)
WHERE a.status='APPROVED';

CREATE INDEX idx_applications_status_date ON applications(status,submitted_on);
EXPLAIN SELECT * FROM applications WHERE status='PENDING'
 AND submitted_on>=CURRENT_DATE-30 AND submitted_on<CURRENT_DATE+1;

CREATE OR REPLACE PROCEDURE pr_assess_pending()
LANGUAGE plpgsql AS $$
DECLARE r RECORD;
BEGIN
 FOR r IN SELECT application_id FROM applications WHERE status='PENDING' ORDER BY application_id
 LOOP
  CALL pr_assess_application(r.application_id);
 END LOOP;
END $$;
