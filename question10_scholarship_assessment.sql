CREATE TABLE students(
 student_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_number VARCHAR(30) NOT NULL UNIQUE,full_name VARCHAR(120) NOT NULL
);
CREATE TABLE applications(
 application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id INT NOT NULL REFERENCES students,
 age_at_application INT NOT NULL CHECK(age_at_application>0),
 monthly_income NUMERIC(12,2) NOT NULL CHECK(monthly_income>=0),
 average_mark NUMERIC(5,2) NOT NULL CHECK(average_mark BETWEEN 0 AND 100),
 submitted_on DATE NOT NULL,
 status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
 CHECK(status IN('PENDING','APPROVED','REJECTED'))
);
CREATE TABLE decision_audit(
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES applications,
 old_status VARCHAR(10) NOT NULL,new_status VARCHAR(10) NOT NULL,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
