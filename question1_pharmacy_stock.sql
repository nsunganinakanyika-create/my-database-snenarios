CREATE OR REPLACE FUNCTION fn_sale_value(p_medicine_id INT,p_quantity INT)
RETURNS NUMERIC(14,2) LANGUAGE plpgsql AS $$
DECLARE v_price NUMERIC(10,2);
BEGIN
 IF p_medicine_id IS NULL OR p_quantity IS NULL OR p_quantity<=0 THEN
  RAISE EXCEPTION 'Medicine ID and a positive quantity are required';
 END IF;
 SELECT unit_price INTO v_price FROM medicines WHERE medicine_id=p_medicine_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown medicine ID %',p_medicine_id; END IF;
 RETURN v_price*p_quantity;
END $$;

CREATE OR REPLACE FUNCTION fn_audit_stock_change()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.stock_qty IS DISTINCT FROM NEW.stock_qty THEN
  INSERT INTO stock_audit(medicine_id,old_qty,new_qty)
  VALUES(NEW.medicine_id,OLD.stock_qty,NEW.stock_qty);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_stock_audit AFTER UPDATE OF stock_qty ON medicines
FOR EACH ROW EXECUTE FUNCTION fn_audit_stock_change();

CREATE OR REPLACE PROCEDURE pr_record_sale(p_medicine_id INT,p_quantity INT,p_sold_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_price NUMERIC(10,2); v_stock INT;
BEGIN
 IF p_quantity IS NULL OR p_quantity<=0 OR p_sold_on IS NULL THEN
  RAISE EXCEPTION 'Quantity must be positive and sale date is required';
 END IF;
 SELECT unit_price,stock_qty INTO v_price,v_stock
 FROM medicines WHERE medicine_id=p_medicine_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown medicine ID %',p_medicine_id; END IF;
 IF v_stock<p_quantity THEN RAISE EXCEPTION 'Insufficient stock: available %, requested %',v_stock,p_quantity; END IF;
 INSERT INTO sales(medicine_id,quantity,unit_price,sold_on)
 VALUES(p_medicine_id,p_quantity,v_price,p_sold_on);
 UPDATE medicines SET stock_qty=stock_qty-p_quantity WHERE medicine_id=p_medicine_id;
END $$;
