CREATE OR REPLACE FUNCTION fn_loan_fine(p_loan_id BIGINT,p_as_of DATE)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
DECLARE v_due DATE; v_return DATE; v_end DATE; v_exists BOOLEAN;
BEGIN
 SELECT due_on,returned_on INTO v_due,v_return FROM loans WHERE loan_id=p_loan_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %',p_loan_id; END IF;
 IF p_as_of IS NULL THEN RAISE EXCEPTION 'As-of date cannot be NULL'; END IF;
 v_end:=LEAST(p_as_of,COALESCE(v_return,p_as_of));
 RETURN GREATEST(v_end-v_due,0)*2.00;
END $$;

CREATE OR REPLACE FUNCTION fn_audit_loan_return()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
  INSERT INTO loan_audit(loan_id,old_returned_on,new_returned_on)
  VALUES(NEW.loan_id,OLD.returned_on,NEW.returned_on);
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_loan_return_audit AFTER UPDATE OF returned_on ON loans
FOR EACH ROW EXECUTE FUNCTION fn_audit_loan_return();

CREATE OR REPLACE PROCEDURE pr_return_loan(p_loan_id BIGINT,p_returned_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_borrowed DATE; v_due DATE; v_return DATE; v_fine NUMERIC(12,2);
BEGIN
 SELECT borrowed_on,due_on,returned_on INTO v_borrowed,v_due,v_return
 FROM loans WHERE loan_id=p_loan_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %',p_loan_id; END IF;
 IF v_return IS NOT NULL THEN RAISE EXCEPTION 'Loan % has already been returned',p_loan_id; END IF;
 IF p_returned_on IS NULL OR p_returned_on<v_borrowed THEN
  RAISE EXCEPTION 'Return date cannot be NULL or before borrowed date';
 END IF;
 v_fine:=GREATEST(p_returned_on-v_due,0)*2.00;
 UPDATE loans SET returned_on=p_returned_on,fine_amount=v_fine WHERE loan_id=p_loan_id;
END $$;

CREATE OR REPLACE VIEW v_overdue_loans AS
SELECT l.loan_id,b.title AS book_title,l.borrower_name,l.due_on,
 fn_loan_fine(l.loan_id,CURRENT_DATE) AS fine_as_of_today
FROM loans l JOIN books b USING(book_id)
WHERE l.returned_on IS NULL AND l.due_on<CURRENT_DATE;

CREATE INDEX idx_loans_book_open ON loans(book_id) WHERE returned_on IS NULL;
EXPLAIN SELECT * FROM loans WHERE book_id=1 AND returned_on IS NULL;

CREATE OR REPLACE PROCEDURE pr_refresh_overdue(p_as_of DATE)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_as_of IS NULL THEN RAISE EXCEPTION 'Snapshot date cannot be NULL'; END IF;
 INSERT INTO overdue_summary(snapshot_date,overdue_count,total_fine)
 SELECT p_as_of,COUNT(*),COALESCE(SUM(GREATEST(p_as_of-due_on,0)*2.00),0)
 FROM loans WHERE returned_on IS NULL AND due_on<p_as_of
 ON CONFLICT(snapshot_date) DO UPDATE SET
 overdue_count=EXCLUDED.overdue_count,total_fine=EXCLUDED.total_fine;
END $$;
CALL pr_refresh_overdue(CURRENT_DATE);
