CREATE TABLE books(book_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,title VARCHAR(160) NOT NULL);
CREATE TABLE loans(
 loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 book_id INT NOT NULL REFERENCES books,
 borrower_name VARCHAR(120) NOT NULL,
 borrowed_on DATE NOT NULL,due_on DATE NOT NULL,
 returned_on DATE NULL,fine_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(fine_amount>=0),
 CHECK(due_on>=borrowed_on),
 CHECK(returned_on IS NULL OR returned_on>=borrowed_on)
);
CREATE TABLE loan_audit(
 audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 loan_id BIGINT NOT NULL REFERENCES loans,
 old_returned_on DATE,new_returned_on DATE,
 changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE overdue_summary(
 snapshot_date DATE PRIMARY KEY,overdue_count BIGINT NOT NULL,total_fine NUMERIC(14,2) NOT NULL
);
